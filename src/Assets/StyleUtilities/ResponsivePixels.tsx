import { Dimensions } from 'react-native';

const BASELINE_WIDTH = 402; // iPhone 17 Pro portrait width (1.000x baseline)
const SCALE_DAMPING = 0.65;
const MIN_SCALE = 0.85;
const MAX_SCALE = 1.15;

export const getResponsiveScaleFactor = (): number => {
  const { width, height } = Dimensions.get('window');
  const portraitWidth = Math.min(width, height) || BASELINE_WIDTH;
  const rawFactor = 1 + (portraitWidth / BASELINE_WIDTH - 1) * SCALE_DAMPING;
  return Math.min(MAX_SCALE, Math.max(MIN_SCALE, rawFactor));
};

export const scaleSize = (size: number): number => {
  if (size === 0) {
    return 0;
  }
  const factor = getResponsiveScaleFactor();
  if (factor === 1) {
    return size;
  }
  const scaled = size * factor;
  if (Number.isInteger(size) && Math.abs(size) >= 2) {
    return Math.round(scaled);
  }
  return Math.round(scaled * 10) / 10;
};

